create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  full_name text not null,
  role text not null default 'Student' check (role in ('Student', 'Teacher', 'Other', 'Admin')),
  auth_email text not null unique,
  contact_email text,
  phone text,
  birthdate date,
  gender text check (gender is null or gender in ('Male', 'Female', 'Other')),
  id_number text,
  department text,
  year_section text,
  street_address text,
  city text,
  province text,
  zip_code text,
  emergency_contact_name text,
  emergency_contact_phone text,
  emergency_contact_relationship text,
  avatar_path text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9._-]{3,30}$')
);

create unique index if not exists profiles_username_ci_unique
  on public.profiles (lower(username));

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null check (category in ('Lecture Halls', 'Classrooms', 'Laboratories', 'Meeting Spaces')),
  room_type text not null,
  capacity integer not null check (capacity > 0),
  floor integer not null check (floor > 0),
  facilities text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.equipment (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null check (category in ('Presentation', 'Audio', 'Computing', 'Supplies')),
  quantity integer not null default 0 check (quantity >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.time_slots (
  id integer generated by default as identity primary key,
  label text not null unique,
  starts_at time not null,
  ends_at time not null,
  sort_order smallint not null unique,
  check (ends_at > starts_at)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  room_id bigint not null references public.rooms(id) on delete restrict,
  booking_date date not null,
  time_slot_id integer not null references public.time_slots(id) on delete restrict,
  purpose text not null check (length(btrim(purpose)) > 0),
  status text not null default 'Pending' check (status in ('Pending', 'Approved', 'Rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists bookings_room_slot_active_unique
  on public.bookings (room_id, booking_date, time_slot_id)
  where status in ('Pending', 'Approved');

create index if not exists bookings_user_date_idx
  on public.bookings (user_id, booking_date desc);

create table if not exists public.booking_equipment (
  booking_id uuid not null references public.bookings(id) on delete cascade,
  equipment_id bigint not null references public.equipment(id) on delete restrict,
  primary key (booking_id, equipment_id)
);

create table if not exists public.teacher_schedules (
  id uuid primary key default gen_random_uuid(),
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  subject text not null check (length(btrim(subject)) > 0),
  section text not null default '',
  day_of_week smallint not null check (day_of_week between 1 and 6),
  time_slot_id integer not null references public.time_slots(id) on delete restrict,
  room_id bigint references public.rooms(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (teacher_id, day_of_week, time_slot_id)
);

create unique index if not exists teacher_schedules_room_slot_unique
  on public.teacher_schedules (room_id, day_of_week, time_slot_id)
  where room_id is not null;

create table if not exists public.damage_reports (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null references public.bookings(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  reported_by uuid not null references public.profiles(id) on delete restrict,
  severity text not null check (severity in ('Minor', 'Moderate', 'Severe')),
  damaged_item text not null,
  details text not null check (length(btrim(details)) > 0),
  reported_on date not null default current_date,
  is_read boolean not null default false,
  acknowledged_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id uuid primary key default gen_random_uuid(),
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  created_at timestamptz not null default now()
);

create index if not exists activity_logs_created_at_idx
  on public.activity_logs (created_at desc);

create or replace function public.is_active_user()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_active
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_active and role = 'Admin'
  );
$$;

revoke all on function public.is_active_user() from public;
revoke all on function public.is_admin() from public;
grant execute on function public.is_active_user() to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  requested_role text := lower(coalesce(nullif(btrim(new.raw_user_meta_data ->> 'role'), ''), 'student'));
  requested_username text := lower(coalesce(nullif(btrim(new.raw_user_meta_data ->> 'username'), ''), split_part(new.email, '@', 1)));
  requested_full_name text := coalesce(nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(new.email, '@', 1));
  generated_username text := requested_username;
  username_suffix integer := 1;
begin
  while exists (select 1 from public.profiles where lower(username) = lower(generated_username)) loop
    generated_username := requested_username || username_suffix;
    username_suffix := username_suffix + 1;
  end loop;

  insert into public.profiles (id, username, full_name, role, auth_email)
  values (
    new.id,
    generated_username,
    requested_full_name,
    case when requested_role in ('teacher', 'other') then initcap(requested_role) else 'Student' end,
    new.email
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

revoke all on function public.handle_new_auth_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

create or replace function public.sync_auth_user_email()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  update public.profiles set auth_email = new.email where id = new.id;
  return new;
end;
$$;

revoke all on function public.sync_auth_user_email() from public, anon, authenticated;
drop trigger if exists on_auth_user_email_changed on auth.users;
create trigger on_auth_user_email_changed
after update of email on auth.users
for each row when (old.email is distinct from new.email)
execute function public.sync_auth_user_email();

