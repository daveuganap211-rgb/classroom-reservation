create or replace function public.check_booking_schedule_conflict()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if new.status in ('Pending', 'Approved') and exists (
    select 1 from public.teacher_schedules s
    where s.room_id = new.room_id
      and s.time_slot_id = new.time_slot_id
      and s.day_of_week = extract(isodow from new.booking_date)::smallint
  ) then
    raise exception 'This room is reserved for a teacher schedule at that time.' using errcode = '23P01';
  end if;
  return new;
end;
$$;

drop trigger if exists bookings_check_schedule_conflict on public.bookings;
create trigger bookings_check_schedule_conflict
before insert or update of room_id, booking_date, time_slot_id, status on public.bookings
for each row execute function public.check_booking_schedule_conflict();

create or replace function public.check_schedule_booking_conflict()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if new.room_id is not null and exists (
    select 1 from public.bookings b
    where b.room_id = new.room_id
      and b.time_slot_id = new.time_slot_id
      and b.booking_date >= current_date
      and extract(isodow from b.booking_date)::smallint = new.day_of_week
      and b.status in ('Pending', 'Approved')
  ) then
    raise exception 'This room already has a booking on that day and time.' using errcode = '23P01';
  end if;
  return new;
end;
$$;

drop trigger if exists schedules_check_booking_conflict on public.teacher_schedules;
create trigger schedules_check_booking_conflict
before insert or update of room_id, day_of_week, time_slot_id on public.teacher_schedules
for each row execute function public.check_schedule_booking_conflict();

